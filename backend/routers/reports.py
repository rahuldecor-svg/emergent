"""PDF compliance report — reportlab."""
from datetime import timedelta
from io import BytesIO
from fastapi import APIRouter, Depends, HTTPException
from fastapi.responses import Response

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import cm
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak,
)

from core.db import db
from core.deps import get_current_user, tenant_filter
from core.security import iso, now_utc

router = APIRouter(prefix="/reports", tags=["reports"])


def _page_frame(canvas, doc):
    """Header + footer on every page."""
    width, height = A4
    canvas.saveState()
    # Header bar
    canvas.setFillColor(colors.HexColor("#111827"))
    canvas.rect(0, height - 1.5 * cm, width, 1.5 * cm, fill=1, stroke=0)
    canvas.setFillColor(colors.white)
    canvas.setFont("Helvetica-Bold", 11)
    canvas.drawString(1.5 * cm, height - 1.0 * cm, "FIRE COMPLIANCE OS")
    canvas.setFont("Helvetica", 8)
    canvas.drawRightString(width - 1.5 * cm, height - 1.0 * cm,
                           "BY SECURRISE SOLUTION PVT LTD (SSPL)")
    # Footer
    canvas.setFillColor(colors.HexColor("#6b7280"))
    canvas.setFont("Helvetica", 7)
    canvas.drawString(1.5 * cm, 1.0 * cm,
                      "Confidential · Generated by Fire Compliance OS · © SSPL")
    canvas.drawRightString(width - 1.5 * cm, 1.0 * cm, f"Page {doc.page}")
    canvas.restoreState()


@router.get("/compliance")
async def compliance_pdf(user: dict = Depends(get_current_user)):
    q = await tenant_filter(user)
    if not q:
        raise HTTPException(400, "Tenant required")

    client = await db.clients.find_one({"id": user["client_id"]}, {"_id": 0})
    client_name = (client or {}).get("name", "Client")
    today = iso(now_utc())[:10]

    total_assets = await db.assets.count_documents(q)
    expired = await db.assets.count_documents({**q, "expiry_date": {"$lt": today}})
    missed = await db.maintenance_tasks.count_documents({**q, "status": "missed"})
    completed = await db.maintenance_tasks.count_documents({**q, "status": "completed"})
    scheduled = await db.maintenance_tasks.count_documents({**q, "status": "scheduled"})
    failed_insp = await db.inspections.count_documents({**q, "overall_result": "fail"})
    score = max(0, 100 - expired * 8 - missed * 4 - failed_insp * 3)
    status = "SAFE" if score >= 85 else ("WARNING" if score >= 60 else "CRITICAL")

    expired_assets = await db.assets.find(
        {**q, "expiry_date": {"$lt": today}}, {"_id": 0}
    ).to_list(50)
    failed = await db.inspections.find(
        {**q, "overall_result": "fail"}, {"_id": 0}
    ).sort("created_at", -1).to_list(20)

    sites = await db.sites.find(q, {"_id": 0}).to_list(200)
    noc_items = await db.noc_checklist.find(q, {"_id": 0}).to_list(1000)
    noc_by_site = {}
    for it in noc_items:
        noc_by_site.setdefault(it["site_id"], []).append(it)

    # --- Build PDF ---
    buf = BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4, topMargin=2.5 * cm, bottomMargin=2 * cm,
        leftMargin=1.5 * cm, rightMargin=1.5 * cm,
    )
    styles = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=styles["Heading1"], fontName="Helvetica-Bold",
                        fontSize=22, spaceAfter=6, textColor=colors.HexColor("#111827"))
    h2 = ParagraphStyle("h2", parent=styles["Heading2"], fontName="Helvetica-Bold",
                        fontSize=13, spaceAfter=4, spaceBefore=12,
                        textColor=colors.HexColor("#111827"))
    body = ParagraphStyle("body", parent=styles["BodyText"], fontSize=10)
    small = ParagraphStyle("small", parent=styles["BodyText"], fontSize=8,
                           textColor=colors.HexColor("#6b7280"))

    score_color = {
        "SAFE": colors.HexColor("#15803d"),
        "WARNING": colors.HexColor("#b45309"),
        "CRITICAL": colors.HexColor("#b91c1c"),
    }[status]

    story = []
    story.append(Paragraph("Fire Safety Compliance Report", h1))
    story.append(Paragraph(f"<b>Client:</b> {client_name} &nbsp;&nbsp; <b>Date:</b> {today}", body))
    story.append(Spacer(1, 0.4 * cm))

    # Score block
    score_tbl = Table(
        [[Paragraph(f"<font size=40 color='{score_color.hexval()}'><b>{score}</b></font>", body),
          Paragraph(f"<b>Fire Safety Score</b><br/>"
                    f"Status: <font color='{score_color.hexval()}'><b>{status}</b></font><br/>"
                    f"Weighting: −8 per expired, −4 per missed, −3 per failed inspection", body)]],
        colWidths=[4 * cm, 12 * cm],
    )
    score_tbl.setStyle(TableStyle([
        ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#d1d5db")),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("BACKGROUND", (0, 0), (0, 0), colors.HexColor("#f9fafb")),
        ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e5e7eb")),
    ]))
    story.append(score_tbl)

    story.append(Paragraph("Summary", h2))
    summary_tbl = Table(
        [["Total assets", total_assets, "Expired assets", expired, "Failed inspections", failed_insp],
         ["Maintenance scheduled", scheduled, "Missed", missed, "Completed", completed]],
        colWidths=[3.2 * cm, 1.2 * cm, 3.2 * cm, 1.2 * cm, 3.2 * cm, 1.2 * cm],
    )
    summary_tbl.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e5e7eb")),
        ("FONTNAME", (0, 0), (-1, -1), "Helvetica"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f9fafb")),
        ("BACKGROUND", (2, 0), (2, -1), colors.HexColor("#f9fafb")),
        ("BACKGROUND", (4, 0), (4, -1), colors.HexColor("#f9fafb")),
    ]))
    story.append(summary_tbl)

    # NOC readiness
    story.append(Paragraph("NOC Readiness (per site)", h2))
    if sites:
        rows = [["Site", "Done", "Total", "Progress", "Status"]]
        for s in sites:
            items = noc_by_site.get(s["id"], [])
            done = sum(1 for x in items if x.get("completed"))
            total = len(items) or 0
            prog = round(done / total * 100) if total else 0
            ready = "READY" if total and done == total else "NOT READY"
            rows.append([s["name"], done, total, f"{prog}%", ready])
        noc_tbl = Table(rows, colWidths=[7 * cm, 2 * cm, 2 * cm, 2.2 * cm, 2.8 * cm])
        noc_tbl.setStyle(TableStyle([
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e5e7eb")),
            ("FONTSIZE", (0, 0), (-1, -1), 9),
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#111827")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ]))
        story.append(noc_tbl)
    else:
        story.append(Paragraph("No sites configured.", small))

    # Expired assets
    story.append(Paragraph("Expired Assets", h2))
    if expired_assets:
        rows = [["Name", "Category", "Serial", "Expired On"]]
        for a in expired_assets[:25]:
            rows.append([a.get("name", "—"), a.get("category", "—").upper(),
                         a.get("serial_number", "—"), a.get("expiry_date", "—")])
        tbl = Table(rows, colWidths=[5.5 * cm, 3 * cm, 3.5 * cm, 3 * cm])
        tbl.setStyle(TableStyle([
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e5e7eb")),
            ("FONTSIZE", (0, 0), (-1, -1), 8),
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#b91c1c")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ]))
        story.append(tbl)
    else:
        story.append(Paragraph("No expired assets. ✓", small))

    # Failed inspections
    story.append(Paragraph("Recent Failed Inspections", h2))
    if failed:
        rows = [["When", "Inspector", "Asset", "Notes"]]
        for f in failed:
            asset = await db.assets.find_one({"id": f.get("asset_id")}, {"_id": 0}) or {}
            rows.append([
                f.get("created_at", "")[:10],
                f.get("inspector_name", "—"),
                asset.get("name", "—"),
                (f.get("notes") or "—")[:60],
            ])
        tbl = Table(rows, colWidths=[2.5 * cm, 3.5 * cm, 4.5 * cm, 5 * cm])
        tbl.setStyle(TableStyle([
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e5e7eb")),
            ("FONTSIZE", (0, 0), (-1, -1), 8),
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#111827")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ]))
        story.append(tbl)
    else:
        story.append(Paragraph("No failed inspections in recent history. ✓", small))

    story.append(Spacer(1, 1 * cm))
    story.append(Paragraph(
        "<i>This report is an authoritative snapshot generated by Fire Compliance OS. "
        "For official NOC filing, download individual certificates from the Document Vault.</i>",
        small,
    ))

    doc.build(story, onFirstPage=_page_frame, onLaterPages=_page_frame)
    pdf = buf.getvalue()
    buf.close()

    filename = f"fire-compliance-{client_name.replace(' ', '_')}-{today}.pdf"
    return Response(
        content=pdf,
        media_type="application/pdf",
        headers={"Content-Disposition": f'attachment; filename="{filename}"'},
    )
